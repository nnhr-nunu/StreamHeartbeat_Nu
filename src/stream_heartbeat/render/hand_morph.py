# これより下（袖）は 2 枚とも同じなので動かさない
MORPH_LIMIT_V = 800.0
# 計算は 1000 画素を 1 にして行う（大きな数の掛け算で桁が落ちないように）
_UNIT = 1000.0
# 対応点を少しだけ緩く通す（近い点どうしで板が暴れないように）
_RELAX = 1e-4

_weights: tuple[list[float], list[float], list[float], list[float]] | None = None


def _kernel(dx: float, dy: float) -> float:
    r2 = dx * dx + dy * dy
    return 0.5 * r2 * math.log(r2) if r2 > 1e-12 else 0.0


def _solve(matrix: list[list[float]], rhs: list[list[float]]) -> list[list[float]]:
    """連立 1 次方程式（部分ピボットのガウスの消去法）。右辺は列ごと。"""
    n = len(matrix)
    a = [row[:] + [col[i] for col in rhs] for i, row in enumerate(matrix)]
    width = n + len(rhs)
    for k in range(n):
        p = max(range(k, n), key=lambda i: abs(a[i][k]))
        a[k], a[p] = a[p], a[k]
        pivot = a[k][k]
        for i in range(k + 1, n):
            f = a[i][k] / pivot
            if f != 0.0:
                row_i = a[i]
                row_k = a[k]
                for j in range(k, width):
                    row_i[j] -= f * row_k[j]
    out = [[0.0] * n for _ in rhs]
    for c in range(len(rhs)):
        for i in range(n - 1, -1, -1):
            s = a[i][n + c]
            for j in range(i + 1, n):
                s -= a[i][j] * out[c][j]
            out[c][i] = s / a[i][i]
    return out


def _fit() -> tuple[list[float], list[float], list[float], list[float]]:
    """対応点を通る板の係数: (点の x, 点の y, x のずれの係数, y のずれの係数)。"""
    global _weights
    if _weights is None:
        xs = [s[0] / _UNIT for s, _t in CLAW_PAIRS]
        ys = [s[1] / _UNIT for s, _t in CLAW_PAIRS]
        n = len(xs)
        size = n + 3
        matrix = [[0.0] * size for _ in range(size)]
        for i in range(n):
            for j in range(n):
                matrix[i][j] = _kernel(xs[i] - xs[j], ys[i] - ys[j])
            matrix[i][i] += _RELAX
            for j, value in enumerate((1.0, xs[i], ys[i])):
                matrix[i][n + j] = value
                matrix[n + j][i] = value
        dx = [(t[0] - s[0]) / _UNIT for s, t in CLAW_PAIRS] + [0.0] * 3
        dy = [(t[1] - s[1]) / _UNIT for s, t in CLAW_PAIRS] + [0.0] * 3
        wx, wy = _solve(matrix, [dx, dy])
        _weights = (xs, ys, wx, wy)
    return _weights


def claw_point(u: float, v: float) -> tuple[float, float]:
    """開いた手の素材の画素 (u, v) が、握った手の素材のどこへ動くか。"""
    if v >= MORPH_LIMIT_V:
        return u, v
    xs, ys, wx, wy = _fit()
    x = u / _UNIT
    y = v / _UNIT
    n = len(xs)
    ox = wx[n] + wx[n + 1] * x + wx[n + 2] * y
    oy = wy[n] + wy[n + 1] * x + wy[n + 2] * y
    for i in range(n):
        k = _kernel(x - xs[i], y - ys[i])
        ox += wx[i] * k
        oy += wy[i] * k
    return u + ox * _UNIT, v + oy * _UNIT
